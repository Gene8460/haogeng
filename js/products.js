// 产品分类的翻译键映射
const CAT_LABEL_KEY = {
  tiller: "products.filter.tiller",
  ditching: "products.filter.ditching",
  pump: "products.filter.pump"
};

let currentCategory = 'all';

function renderProducts(category) {
  currentCategory = category || currentCategory;
  const grid = document.getElementById('productGrid');
  if (!grid) return;

  const lang = currentLang || 'en';
  const list = PRODUCTS.filter(p => currentCategory === 'all' || p.cat === currentCategory);

  grid.innerHTML = list.map(p => {
    const name = (p.name && p.name[lang]) || p.name.en;
    const specs = (p.specs && p.specs[lang]) ? p.specs[lang] : (p.specs && p.specs.en) || [];
    // 列表卡片按品类精选展示行，其余详情页展示
    let cardSpecs;
    if (p.cat === 'tiller' || p.cat === 'ditching') {
      cardSpecs = specs.slice(0, 2);
    } else if (p.cat === 'pump') {
      // 抽水机只保留：发动机 / 进出水口径 / 排量
      const find = (kws) => specs.find(s => kws.some(kw => s.indexOf(kw) >= 0));
      const engine = find(['发动机', 'Engine', 'Motor', 'Двигатель', 'Moteur']);
      const port = find(['进出水口径', 'Inlet/outlet', 'Diámetro', 'Патрубки', 'Diamètre']);
      const disp = find(['排量', 'Displacement', 'Cilindrada', 'Объём', 'Cylindrée']);
      cardSpecs = [engine, port, disp].filter(Boolean);
    } else {
      cardSpecs = specs;
    }
    const catLabel = t(CAT_LABEL_KEY[p.cat]) || p.cat;
    const inquire = t('products.inquire') || 'Send Inquiry';
    const imgHtml = p.img
      ? `<div class="product-img"><picture><source srcset="images/${p.img.replace(/\.(jpg|jpeg|png)$/i, '.webp')}" type="image/webp"><img src="images/${p.img}" alt="${name}" loading="lazy" style="width:auto;height:auto;max-width:100%;max-height:100%;object-fit:contain;"></picture></div>`
      : `<div class="product-img">📷 <span style="margin-left:8px">${name}</span></div>`;

    return `
      <div class="product-card" data-cat="${p.cat}">
        <a class="product-link" href="product.html?id=${encodeURIComponent(p.id)}">
          ${imgHtml}
          <div class="product-body">
            <span class="product-cat">${catLabel}</span>
            <h3 class="product-name">${name}</h3>
            <div class="product-model">${p.model}</div>
            <ul class="product-specs">${cardSpecs.map(s => `<li>· ${s}</li>`).join('')}</ul>
            <span class="product-cta">${inquire} →</span>
          </div>
        </a>
      </div>`;
  }).join('');
}

// 初始化分类过滤按钮
function initFilters() {
  document.querySelectorAll('.filter-btn').forEach(btn => {
    btn.addEventListener('click', () => {
      document.querySelectorAll('.filter-btn').forEach(b => b.classList.remove('active'));
      btn.classList.add('active');
      renderProducts(btn.getAttribute('data-cat'));
    });
  });
}